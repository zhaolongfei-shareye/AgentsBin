const FALLBACK = STRINGS.en;

function currentLang() {
  return localStorage.getItem("agentsbin-lang") || localStorage.getItem("wf_lang") || "en";
}

function applyLang(lang) {
  const dict = STRINGS[lang] || FALLBACK;
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) el.textContent = dict[key];
  });
  document.documentElement.lang = lang;
  const sha = document.getElementById("shaValue");
  if (sha) sha.textContent = SHA256;
}

function track(kind, extra = {}) {
  if (location.protocol !== "https:" && location.protocol !== "http:") return;
  const payload = JSON.stringify({
    kind,
    name: "watermark_factory",
    version: "1.0.2",
    source: "web",
    product: "wf",
    ...extra
  });
  if (navigator.sendBeacon) {
    navigator.sendBeacon("/api/track", new Blob([payload], { type: "application/json" }));
  } else {
    fetch("/api/track", { method: "POST", headers: { "Content-Type": "application/json" }, body: payload });
  }
}

document.addEventListener("DOMContentLoaded", () => {
  const select = document.getElementById("langSelect");
  select.value = currentLang();
  applyLang(select.value);
  select.addEventListener("change", () => {
    localStorage.setItem("agentsbin-lang", select.value);
    localStorage.setItem("wf_lang", select.value);
    applyLang(select.value);
  });
  track("page_view");
  document.querySelectorAll("[data-track='download']").forEach((el) => {
    el.addEventListener("click", () => track("download"));
  });
});
